"""
Verify sources/linked_resources.json against each resource's host and write docs/linked-resources.md.

    python scripts/check_linked_resources.py [--no-doc]

For every resource this records what the host itself reports today: that it exists, its title, licence, the
immutable identifier of what was seen (Zenodo file checksums, Hugging Face commit, PyPI version and sdist hash,
GitHub commit) and the date checked. Nothing is downloaded or stored. Licence and `redistributable` are filled
from the host only when the registry leaves them empty; a hand-set value is never overwritten.
Standard library only; never spends API credit.
"""
import argparse
import datetime
import json
import pathlib
import time
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
REG = ROOT / "sources/linked_resources.json"
DOC = ROOT / "docs/linked-resources.md"
UA = {"User-Agent": "text2wetlab provenance check (research)"}
PERMISSIVE = ("mit", "apache-2.0", "bsd", "cc-by-4.0", "cc0", "cc-by 4.0", "cc by 4.0", "unlicense", "isc")


def get(url, tries=3):
    err = ""
    for attempt in range(tries):            # hosts rate-limit bursts: back off and retry before calling it missing
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40) as r:
                return json.load(r)
        except Exception as e:
            err = f"{type(e).__name__}: {e}"[:120]
            time.sleep(4 * (attempt + 1))
    return {"_error": err}


def zenodo(rid):
    j = get(f"https://zenodo.org/api/records/{rid}")
    if "_error" in j:
        return {"exists": False, "error": j["_error"]}
    m, files = j.get("metadata", {}), j.get("files", [])
    return {"exists": True, "title": m.get("title"), "doi": j.get("doi"), "published": m.get("publication_date"),
            "version": m.get("version"), "licence_reported": (m.get("license") or {}).get("id"),
            "resource_type": (m.get("resource_type") or {}).get("type"), "files": len(files),
            "bytes": sum(f.get("size") or 0 for f in files),
            "checksums": [f"{f.get('key')}: {f.get('checksum')}" for f in files[:5]]}


def huggingface(rid):
    j = get(f"https://huggingface.co/api/datasets/{rid}")
    if "_error" in j:
        return {"exists": False, "error": j["_error"]}
    card = j.get("cardData") or {}
    return {"exists": True, "commit": j.get("sha"), "last_modified": j.get("lastModified"), "licence_reported": card.get("license"),
            "files": len(j.get("siblings", [])), "gated": j.get("gated"), "private": j.get("private"), "downloads": j.get("downloads")}


def pypi(name):
    j = get(f"https://pypi.org/pypi/{name}/json")
    if "_error" in j:
        return {"exists": False, "error": j["_error"]}
    info = j.get("info", {})
    sdist = next((u for u in j.get("urls", []) if u.get("packagetype") == "sdist"), {})
    lic = info.get("license") or next((c.split("::")[-1].strip() for c in info.get("classifiers", []) if c.startswith("License")), None)
    return {"exists": True, "version": info.get("version"), "licence_reported": lic, "released": sdist.get("upload_time"),
            "sdist_sha256": (sdist.get("digests") or {}).get("sha256")}


def github(repo):
    j = get(f"https://api.github.com/repos/{repo}")
    if "_error" in j:
        return {"exists": False, "error": j["_error"]}
    head = get(f"https://api.github.com/repos/{repo}/commits/{j.get('default_branch')}")
    return {"exists": True, "commit": head.get("sha"), "pushed": j.get("pushed_at"), "archived": j.get("archived"),
            "licence_reported": (j.get("license") or {}).get("spdx_id"), "stars": j.get("stargazers_count")}


def doi(d):
    j = get("https://api.crossref.org/works/" + urllib.parse.quote(d))
    if "_error" in j:
        return {"exists": False, "error": j["_error"]}
    m = j.get("message", {})
    return {"exists": True, "title": " ".join((m.get("title") or [""])[0].split()), "journal": (m.get("container-title") or [""])[0],
            "year": ((m.get("issued") or {}).get("date-parts") or [[None]])[0][0],
            "licence_reported": next((l.get("URL") for l in m.get("license", [])), None)}


def url(u):
    try:
        with urllib.request.urlopen(urllib.request.Request(u, headers=UA, method="HEAD"), timeout=40) as r:
            return {"exists": r.status < 400, "status": r.status}
    except Exception as e:
        return {"exists": False, "error": f"{type(e).__name__}: {e}"[:120]}


HOSTS = {"zenodo": zenodo, "huggingface": huggingface, "pypi": pypi, "github": github, "doi": doi}


def render(reg):
    by_task = {}
    for r in reg["resources"]:
        for t in r["tasks"]:
            by_task.setdefault(t, []).append(r)
    L = ["# Datasets, outcome models and simulators linked to each task", "",
         "Generated by `scripts/check_linked_resources.py` from `sources/linked_resources.json`. Links and metadata only;",
         "nothing third-party is stored here. **Direct** = from the task's own source paper; **related** = same method, different study.",
         "\"Pinned\" is what the host reported on the checked date (Zenodo checksum count, Hugging Face or GitHub commit, PyPI version).", "",
         f"Found: {reg['found']}", ""]

    def table(rows):
        out = ["| Resource | Kind | Relation | What it is | Licence | Redistributable | Pinned | Checked |", "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            v = r.get("verification", {})
            pin = (v.get("commit") or "")[:10] or (f"v{str(v['version']).lstrip('v')}" if v.get("version") else "") or (f"{v['files']} files" if v.get("files") else "") \
                or (str(v.get("year")) if v.get("year") else "")
            ok = v.get("checked", "") if v.get("exists") else f"NOT FOUND {v.get('checked', '')}"
            out.append(f"| [{r['name']}]({r['url']}) | {', '.join(r['kind'])} | {r['relation']} | {r['what']} | "
                       f"{r.get('licence') or 'not stated'} | {r.get('redistributable')} | {pin} | {ok} |")
        return out

    for t in sorted(k for k in by_task if k != "all"):
        L += [f"## `{t}`", ""] + table(by_task[t]) + [""]
    if "all" in by_task:
        L += ["## All tasks (robot-level datasets and simulators)", ""] + table(by_task["all"]) + [""]
    L += ["## Gaps", ""] + [f"- **{', '.join(g['tasks'])}:** {g['finding']}" for g in reg["gaps"]] + [""]
    L += ["## Notes on individual resources", ""] + [f"- **{r['name']}:** {r['notes']}" for r in reg["resources"] if r.get("notes")] + [""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-doc", action="store_true")
    a = ap.parse_args()
    reg = json.loads(REG.read_text())
    today = datetime.date.today().isoformat()
    for r in reg["resources"]:
        v = HOSTS[r["host"]](r["identifier"]) if r["host"] in HOSTS else url(r["url"])
        v["checked"] = today
        r["verification"] = v
        rep = str(v.get("licence_reported") or "")
        if not r.get("licence") and rep:
            r["licence"] = rep
            if r.get("redistributable") == "unknown":
                r["redistributable"] = "yes" if rep.lower().startswith(PERMISSIVE) else "unknown"
        print(f"{r['id']}: {'ok' if v.get('exists') else 'NOT FOUND'} | licence {rep or '-'} | "
              f"{v.get('commit', '')[:10] if v.get('commit') else v.get('version') or v.get('files') or v.get('year') or ''}")
    REG.write_text(json.dumps(reg, indent=1, ensure_ascii=False) + "\n")
    if not a.no_doc:
        DOC.write_text(render(reg))
        print("wrote", DOC.relative_to(ROOT))


if __name__ == "__main__":
    main()
